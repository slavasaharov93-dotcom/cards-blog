errors = []
for slug, edits in EDITS.items():
    path = ART / f"{slug}.json"
    data = json.load(open(path, encoding="utf-8"))
    body = data["bodyMarkdown"]
    for old, new in edits:
        cnt = body.count(old)
        if cnt != 1:
            errors.append(f"{slug}: ожидалось 1 совпадение, найдено {cnt} для: {old[:60]}...")
            continue
        body = body.replace(old, new)
    data["bodyMarkdown"] = body
    json.dump(data, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"ok: {slug} ({len(edits)} правок)")

if errors:
    print("\nОШИБКИ:")
    for e in errors:
        print(" -", e)
    sys.exit(1)
